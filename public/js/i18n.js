let _lang = localStorage.getItem('uis-lang') || 'ja';

function t(key, vars = {}) {
  const locale = LOCALES[_lang] || LOCALES.ja;
  const str = locale[key] ?? LOCALES.ja[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : ''));
}

function setLang(lang) {
  if (!LOCALES[lang]) return;
  _lang = lang;
  localStorage.setItem('uis-lang', lang);
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
  applyDOM();
  window.Bus?.emit('lang-changed');
}

function getLang() { return _lang; }

